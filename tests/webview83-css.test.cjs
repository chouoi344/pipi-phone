'use strict';
const test = require('node:test');
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const os = require('node:os');
const {execFileSync} = require('node:child_process');
const {compile, build, normalizeLF} = require('../scripts/build-webview83-css.cjs');

test('the shipped legacy sheet stays in sync with every linked source stylesheet', () => {
  assert.equal(normalizeLF(fs.readFileSync(path.join(__dirname, '../public/webview83.css'), 'utf8')), build());
});

test('source hash and generated bytes are identical for LF and CRLF checkouts', () => {
  const read = file => normalizeLF(fs.readFileSync(file, 'utf8'));
  const lf = build(read), crlf = build(file => read(file).replace(/\n/g, '\r\n'));
  assert.equal(crlf, lf);
  assert.doesNotMatch(lf, /\r/);
});

test('the release --check command accepts LF or CRLF input and output files', () => {
  const fixture = fs.mkdtempSync(path.join(os.tmpdir(), 'pipi-css-newlines-'));
  try {
    const sourceRoot = path.resolve(__dirname, '..');
    const html = fs.readFileSync(path.join(sourceRoot, 'public/index.html'), 'utf8');
    const linked = [...html.matchAll(/\shref="\/([^"?]+\.css)(?:\?[^"\s]*)?"/g)]
      .map(match => match[1]).filter(file => !file.startsWith('vendor/') && !file.startsWith('fonts/'));
    const files = ['scripts/build-webview83-css.cjs', 'scripts/webview83-fallbacks.css',
      'public/index.html', 'public/webview83.css', ...linked.map(file => 'public/' + file)];
    for (const newline of ['\n', '\r\n']) {
      for (const file of files) {
        const target = path.join(fixture, file);
        fs.mkdirSync(path.dirname(target), {recursive:true});
        fs.writeFileSync(target, normalizeLF(fs.readFileSync(path.join(sourceRoot, file), 'utf8')).replace(/\n/g, newline));
      }
      assert.match(execFileSync(process.execPath, ['scripts/build-webview83-css.cjs', '--check'],
        {cwd:fixture, encoding:'utf8'}), /matches linked source stylesheets/);
    }
  } finally { fs.rmSync(fixture, {recursive:true, force:true}); }
});

test('legacy compilation keeps later skin overrides after the expanded base rule', () => {
  const css = compile(':is(#view,.navigation-snapshot) .field{padding-inline:8px;color:red}@media(min-width:650px){.field{color:blue}}');
  assert(css.indexOf('color:red') < css.indexOf('color:blue'));
  assert.match(css, /#view \.field,\.navigation-snapshot \.field\{padding-left:8px;padding-right:8px;color:red\}/);
  assert.match(css, /@media\(min-width:650px\)\{\.field\{color:blue\}/);
});

test('calc, custom property fallbacks and important survive directional expansion', () => {
  const css = compile('.overlay{inset:auto var(--left,0px) calc(10vh + 4px)!important;padding-block:10px 12px;max-height:calc(var(--app-height,100dvh) - 48px)}');
  assert.match(css, /top:auto!important;right:var\(--left,0px\)!important;bottom:calc\(10vh \+ 4px\)!important;left:var\(--left,0px\)!important/);
  assert.match(css, /padding-top:10px;padding-bottom:12px/);
  assert.match(css, /max-height:calc\(var\(--app-height,100vh\) - 48px\)/);
});

test('complex selector branches retain the subject and local interaction states', () => {
  const css = compile('.root :is(.button-area>.primary,.primary-btn){color:red}#overlay:has(>.model-sheet){pointer-events:auto}.row:has(.decorative),.row.active{color:green}');
  assert.match(css, /\.root \.button-area>\.primary,\.root \.primary-btn/);
  assert.match(css, /#overlay\.has-model-sheet\{pointer-events:auto\}/);
  assert.match(css, /\.row.active\{color:green\}/);
  assert.doesNotMatch(css, /:has\(/);
  assert.throws(() => compile('.item:is(.parent .child,.plain){color:red}'), /Review attached complex/);
});

test('quoted SVG data and braces do not split CSS rules or declarations', () => {
  const css = compile('.icon{background:url("data:image/svg+xml,<svg>{x;y}</svg>");content:"a;b"}.next{color:blue}');
  assert.match(css, /content:"a;b"/);
  assert.match(css, /\.next\{color:blue\}/);
});

"""Build the two Noto Sans SC subsets and CSS for the current web font."""

import argparse
import hashlib
from itertools import groupby
from pathlib import Path

from fontTools import subset
from fontTools.ttLib import TTFont


def common_characters():
    # GB2312 zones 16–87 contain the 6763 commonly used Chinese ideographs.
    chinese = set()
    for lead in range(0xB0, 0xF8):
        for trail in range(0xA1, 0xFF):
            try:
                chinese.add(ord(bytes([lead, trail]).decode('gb2312')))
            except UnicodeDecodeError:
                continue
    if len(chinese) != 6763:
        raise ValueError('GB2312 did not provide 6763 ideographs')
    return (chinese | set(range(0x20, 0x7F)) | set(range(0x2000, 0x2070))
            | set(range(0x3000, 0x3040)) | set(range(0xFF01, 0xFF61))
            | set(map(ord, '\u00a0·￥¥→←↑↓✓×°℃≠≤≥⋯')))


def unicode_ranges(codepoints):
    ranges = []
    for _, entries in groupby(enumerate(sorted(codepoints)), lambda item: item[1] - item[0]):
        values = [codepoint for _, codepoint in entries]
        one = f'U+{values[0]:X}'
        ranges.append(f'{one}-{values[-1]:X}' if len(values) > 1 else one)
    return ','.join(ranges)


def build(source, output):
    with TTFont(source, recalcTimestamp=False) as original:
        original_codepoints = set(original.getBestCmap())
        common = original_codepoints & common_characters()
        uncommon = original_codepoints - common
        weight = next(axis for axis in original['fvar'].axes if axis.axisTag == 'wght')
        axes = (weight.minValue, weight.defaultValue, weight.maxValue)
    output.mkdir(parents=True, exist_ok=True)
    css = ['/* Generated by scripts/split-chinese-font.py. */']
    for group, codepoints in [('common', common), ('extended', uncommon)]:
        name = f'NotoSansSC-{group}.woff2'
        options = subset.Options()
        options.flavor = 'woff2'
        options.recalc_timestamp = False
        options.layout_features = ['*']
        options.name_IDs = ['*']
        options.name_languages = ['*']
        options.retain_all_variation_sequences = True
        font = subset.load_font(source, options)
        subsetter = subset.Subsetter(options=options)
        subsetter.populate(unicodes=codepoints)
        subsetter.subset(font)
        # Distinguish the subset files; the application's CSS family stays stable.
        for record in font['name'].names:
            replacements = {1: 'Pipi Noto SC', 3: f'PipiNotoSC-{group}',
                            4: 'Pipi Noto SC', 6: 'PipiNotoSC', 16: 'Pipi Noto SC', 25: 'PipiNotoSC'}
            if record.nameID in replacements:
                record.string = replacements[record.nameID]
        subset.save_font(font, output / name, options)
        with TTFont(output / name) as result:
            result_weight = next(axis for axis in result['fvar'].axes if axis.axisTag == 'wght')
            if set(result.getBestCmap()) != codepoints or (
                result_weight.minValue, result_weight.defaultValue, result_weight.maxValue
            ) != axes:
                raise ValueError(f'Subset {name} changed Unicode coverage or font weights')
        face = ('@font-face{font-family:"Noto Sans SC";'
                f'src:url("/fonts/{name}") format("woff2");'
                f'font-style:normal;font-weight:{axes[0]:g} {axes[2]:g};font-display:swap;'
                f'unicode-range:{unicode_ranges(codepoints)}' + '}')
        css.append(face)
        print(f'{name}: {len(codepoints)} characters, {(output / name).stat().st_size} bytes')
    (output / 'noto-sans-sc.css').write_text('\n'.join(css) + '\n', encoding='utf-8', newline='\n')


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('source', type=Path, help='Original Noto Sans SC 2.004 variable TTF or WOFF2')
    parser.add_argument('--output', type=Path, default=Path(__file__).resolve().parents[1] / 'public' / 'fonts')
    args = parser.parse_args()
    print(f'{args.source}: {hashlib.sha256(args.source.read_bytes()).hexdigest()}')
    build(args.source, args.output)


if __name__ == '__main__':
    main()
